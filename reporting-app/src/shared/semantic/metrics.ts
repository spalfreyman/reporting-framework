/**
 * The metric registry.
 *
 * Metric ids encode their BUCKETING RULE where it matters: `revenue.net@orderdate` is
 * restated when a refund lands 40 days later; `revenue.net@cashdate` buckets on the date
 * money actually moved and is never restated. Finance wants one, merchandising wants the
 * other, and forcing a single number to serve both is the single largest source of
 * "your report doesn't match my spreadsheet". Making it a type-level choice means nobody
 * can be vague about it.
 *
 * Never rename an id. Add the new one and mark the old `deprecated`.
 */

