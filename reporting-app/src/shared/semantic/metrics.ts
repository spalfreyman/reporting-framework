export const METRICS: Readonly<Record<string, MetricDef>> = Object.freeze(
  Object.fromEntries(defs.map((m) => [m.id, Object.freeze(m)]))
);

export const getMetric = (id: string): MetricDef | undefined => METRICS[id];

export const isMoneyMetric = (id: string): boolean => METRICS[id]?.valueType === 'money';

export const BASE_METRIC_IDS: readonly string[] = Object.freeze(
  defs.filter((m): m is BaseMetric => m.kind === 'base').map((m) => m.id)
);

export const DERIVED_METRIC_IDS: readonly string[] = Object.freeze(
  defs.filter((m): m is DerivedMetric => m.kind === 'derived').map((m) => m.id)
);
